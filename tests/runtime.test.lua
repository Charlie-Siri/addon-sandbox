end)

test("visibility and OnShow/OnHide", function()
    local parent = CreateFrame("Frame", nil, UIParent)
    local child = CreateFrame("Frame", nil, parent)
    local shows, hides = 0, 0
    child:SetScript("OnShow", function() shows = shows + 1 end)
    child:SetScript("OnHide", function() hides = hides + 1 end)
    parent:Hide()
    eq(child:IsShown(), true); eq(child:IsVisible(), false); eq(hides, 1, "OnHide via parent")
    parent:Show()
    eq(shows, 1, "OnShow via parent")
end)

test("events dispatch in registration order", function()
    local order = {}
    local f1, f2 = CreateFrame("Frame"), CreateFrame("Frame")
    f1:RegisterEvent("SANDBOX_TEST_EVENT")
    f2:RegisterEvent("SANDBOX_TEST_EVENT")
    f1:SetScript("OnEvent", function(_, e, arg) order[#order + 1] = "1" .. arg end)
    f2:SetScript("OnEvent", function(_, e, arg) order[#order + 1] = "2" .. arg end)
    S.FireEvent("SANDBOX_TEST_EVENT", "x")
    eq(table.concat(order, ","), "1x,2x")
    f1:UnregisterEvent("SANDBOX_TEST_EVENT")
    S.FireEvent("SANDBOX_TEST_EVENT", "y")
    eq(table.concat(order, ","), "1x,2x,2y")
end)

test("timers and tickers", function()
    local fired, ticks = false, 0
    C_Timer.After(0.1, function() fired = true end)
    local ticker = C_Timer.NewTicker(0.1, function() ticks = ticks + 1 end, 3)
    local timer = C_Timer.NewTimer(0.05, function() error("cancelled timer ran") end)
    timer:Cancel()
    S.Advance(0.5)
    eq(fired, true, "After fired"); eq(ticks, 3, "ticker iterations"); eq(ticker:IsCancelled(), false)
end)

test("SavedVariables serializer round-trips", function()
    SandboxTestDB = { name = 'quote " and \\ and\nnewline', n = 216.6666666666667, list = { 1, "two", false },
        nested = { [15347] = 5000, deep = { ok = true } }, [3] = "three" }
    local text = S.SerializeVariables({ "SandboxTestDB" })
    local env = {}
    local fn = assert(loadstring(text))
    setfenv(fn, env)
    fn()
    local copy = env.SandboxTestDB
    eq(copy.name, SandboxTestDB.name, "string escapes")
    eq(copy.n, SandboxTestDB.n, "float precision")
    eq(copy.list[2], "two"); eq(copy.list[3], false)
    eq(copy.nested[15347], 5000); eq(copy.nested.deep.ok, true); eq(copy[3], "three")
end)

test("button click and check toggle", function()
    local clicks = 0
    local b = CreateFrame("Button", nil, UIParent, "UIPanelButtonTemplate")
    b:SetPoint("TOPLEFT", 50, -50)
    b:SetText("Go")
    b:SetScript("OnClick", function(_, button) clicks = clicks + 1; eq(button, "LeftButton") end)
    click(b)
    eq(clicks, 1, "OnClick")
    b:Disable()
    click(b)
    eq(clicks, 1, "disabled buttons don't click")
    local cb = CreateFrame("CheckButton", nil, UIParent, "UICheckButtonTemplate")
    cb:SetPoint("TOPLEFT", 50, -100)
    click(cb)
    eq(cb:GetChecked(), true, "check toggles before OnClick")
end)

test("edit box typing", function()
    local eb = CreateFrame("EditBox", nil, UIParent, "InputBoxTemplate")
    eb:SetSize(120, 20)
    eb:SetPoint("TOPLEFT", 50, -150)
    eb:SetAutoFocus(false)
    local changes = 0
    eb:SetScript("OnTextChanged", function(_, user) if user then changes = changes + 1 end end)
    click(eb)
    eq(eb:HasFocus(), true, "focus on click")
    S.Char("ab")
    S.KeyDown("BACKSPACE")
    eq(eb:GetText(), "a"); eq(changes, 2, "user OnTextChanged")
    S.KeyDown("ESCAPE")
    eq(eb:HasFocus(), false, "InputBoxTemplate clears focus on Escape")
    eb:SetNumeric(true)
    eb:SetText("")
    eb:SetFocus()
    S.Char("x"); S.Char("7")
    eq(eb:GetText(), "7", "numeric filter")
    eb:ClearFocus()
end)

