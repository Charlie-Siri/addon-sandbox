-- Runtime self-tests, loaded as an addon by scripts/test.ts. Each failure becomes an error in the report.
local S = SANDBOX
local passed = 0

local function test(name, fn)
    local ok, err = pcall(fn)
    if ok then passed = passed + 1 else error(("[%s] %s"):format(name, tostring(err)), 0) end
end
local function eq(a, b, msg)
    if a ~= b then error(("%s: expected %s, got %s"):format(msg or "value", tostring(b), tostring(a)), 2) end
end
local function near(a, b, msg) if math.abs((a or -1e9) - b) > 0.01 then eq(a, b, msg) end end
local function click(frame)
    local x, y = frame:GetCenter()
    S.MouseMove(x, S.screenH - y)
    S.MouseDown("LeftButton")
    S.MouseUp("LeftButton")
end

test("strsplit uses every delimiter character", function()
    local a, b, c = strsplit(",;", "x,y;z")
    eq(a, "x"); eq(b, "y"); eq(c, "z")
    local p, q = strsplit(" ", "one two three", 2)
    eq(p, "one"); eq(q, "two three")
    eq(strjoin("-", "a", "b", "c"), "a-b-c")
    eq(strtrim("  hi \n"), "hi")
    eq(strtrim("xxhixx", "x"), "hi")
end)

