test("item data loads asynchronously", function()
    local id = 987654
    eq(GetItemInfo(id), nil, "not cached on first call")
    local got
    local f = CreateFrame("Frame")
    f:RegisterEvent("GET_ITEM_INFO_RECEIVED")
    f:SetScript("OnEvent", function(_, _, itemID) got = itemID end)
    S.Advance(0.2)
    eq(got, id, "GET_ITEM_INFO_RECEIVED")
    assert(GetItemInfo(id), "cached afterwards")
end)

test("hooksecurefunc runs after the original", function()
    local order = {}
    SandboxTestFn = function(x) order[#order + 1] = "orig" .. x return "r" end
    hooksecurefunc("SandboxTestFn", function(x) order[#order + 1] = "hook" .. x end)
    eq(SandboxTestFn(1), "r")
    eq(table.concat(order, ","), "orig1,hook1")
end)

